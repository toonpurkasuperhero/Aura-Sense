#!/usr/bin/env bash
# Flash and test the real ESP32 sensor box from this laptop.
#
#   ./scripts/flash.sh doctor          check laptop IP, backend, firewall, USB port permissions
#   ./scripts/flash.sh check  [PORT]   flash the hardware self-test and open the serial monitor
#   ./scripts/flash.sh node   [PORT]   flash the real AuraSense firmware and open the serial monitor
#   ./scripts/flash.sh monitor [PORT]  serial monitor only (Ctrl+C to quit)
#
# Optional env overrides: WIFI_SSID, WIFI_PASS, NODE_ID (default esp32_rig), BACKEND_IP, RPM_HINT
set -u
cd "$(dirname "$0")/.."
FW=firmware
CLI="${ARDUINO_CLI:-$(command -v arduino-cli || echo "$HOME/.local/bin/arduino-cli")}"
FQBN="esp32:esp32:esp32"
CFG="$FW/aurasense_node/config.h"

red() { printf '\033[31m%s\033[0m\n' "$*"; }
grn() { printf '\033[32m%s\033[0m\n' "$*"; }
ylw() { printf '\033[33m%s\033[0m\n' "$*"; }

laptop_ip() {
  [ -n "${BACKEND_IP:-}" ] && { echo "$BACKEND_IP"; return; }
  # Prefer the Wi-Fi interface (the ESP32 is on Wi-Fi), then the default-route address.
  local wifi
  wifi=$(nmcli -t -f DEVICE,TYPE,STATE dev 2>/dev/null | awk -F: '$2=="wifi" && $3=="connected"{print $1; exit}')
  if [ -n "$wifi" ]; then ip -4 -o addr show "$wifi" | awk '{print $4}' | cut -d/ -f1 | head -1; return; fi
  ip -4 route get 8.8.8.8 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src") print $(i+1)}' | head -1
}

find_port() {
  [ -n "${1:-}" ] && { echo "$1"; return; }
  ls /dev/ttyUSB* /dev/ttyACM* 2>/dev/null | head -1
}

cfg_get() { grep -E "#define $1 " "$CFG" 2>/dev/null | sed -E 's/.*"(.*)".*/\1/'; }

write_config() {
  local ip ssid pass node rpm
  ip=$(laptop_ip)
  ssid="${WIFI_SSID:-$(cfg_get CFG_WIFI_SSID)}"; pass="${WIFI_PASS:-$(cfg_get CFG_WIFI_PASS)}"
  node="${NODE_ID:-$(cfg_get CFG_NODE_ID)}"; node="${node:-esp32_rig}"
  rpm="${RPM_HINT:-$(grep -E '#define CFG_RPM_HINT' "$CFG" 2>/dev/null | awk '{print $3}')}"; rpm="${rpm:-1440.0}"
  if [ -z "$ssid" ] || [ "$ssid" = "YOUR_WIFI" ]; then
    read -r -p "Wi-Fi name (2.4 GHz) the ESP32 should join: " ssid
    read -r -s -p "Wi-Fi password: " pass; echo
  fi
  cat > "$CFG" <<EOF
// Local settings for this sensor box. Generated by scripts/flash.sh. NOT committed (see .gitignore).
#pragma once
#define CFG_WIFI_SSID   "$ssid"
#define CFG_WIFI_PASS   "$pass"
#define CFG_BACKEND_URL "http://$ip:8000"
#define CFG_NODE_ID     "$node"
#define CFG_RPM_HINT    $rpm
EOF
  cp "$CFG" "$FW/sensor_check/config.h"
  grn "config.h: Wi-Fi '$ssid', backend http://$ip:8000, node '$node'"
}

doctor() {
  local ok=1 ip port
  echo "== AuraSense hardware doctor"
  ip=$(laptop_ip)
  echo "Laptop IP the ESP32 will call : ${ip:-none}"
  local wifi_state
  wifi_state=$(nmcli -t -f DEVICE,TYPE,STATE dev 2>/dev/null | awk -F: '$2=="wifi"{print $1" "$3; exit}')
  echo "Laptop Wi-Fi adapter          : ${wifi_state:-not found}"
  if ! nmcli -t -f TYPE,STATE dev 2>/dev/null | grep -q '^wifi:connected'; then
    ylw "  ! The laptop is not on Wi-Fi. Join the SAME Wi-Fi/hotspot as the ESP32 (or make sure that Wi-Fi"
    ylw "    can route to $ip). Easiest: phone hotspot (2.4 GHz) for both."
  fi
  if curl -s -m 3 "http://127.0.0.1:8000/api/health" >/dev/null; then grn "Backend on :8000              : running"
  else red "Backend on :8000              : NOT running -> ./scripts/run_all.sh"; ok=0; fi
  if [ -n "$ip" ] && curl -s -m 3 "http://$ip:8000/api/health" >/dev/null; then grn "Backend via $ip           : reachable from this machine"
  else red "Backend via $ip           : not reachable"; ok=0; fi
  if systemctl is-active --quiet ufw 2>/dev/null; then
    ylw "Firewall (ufw)                : ACTIVE. If the self-test shows BACKEND FAIL, run once:"
    ylw "                                  sudo ufw allow 8000/tcp"
  else grn "Firewall (ufw)                : inactive"; fi
  port=$(find_port "")
  if [ -z "$port" ]; then ylw "ESP32 USB port                : none found (plug in the board with a DATA micro-USB cable)"
  elif [ -w "$port" ]; then grn "ESP32 USB port                : $port (writable)"
  else
    red "ESP32 USB port                : $port is NOT writable by $(whoami). Run once:"
    red "                                  sudo usermod -aG dialout $(whoami)   # then log out and back in"
    red "                                or, for this session only:  sudo chmod a+rw $port"
    ok=0
  fi
  [ -x "$CLI" ] && grn "arduino-cli                   : $CLI" || { red "arduino-cli not found"; ok=0; }
  [ $ok = 1 ] && grn "== ready" || red "== fix the red items above"
}

flash() {
  local sketch=$1 port
  port=$(find_port "${2:-}")
  [ -z "$port" ] && { red "No ESP32 found on /dev/ttyUSB* or /dev/ttyACM*. Plug it in (data cable) and retry."; exit 1; }
  [ -w "$port" ] || { red "$port not writable. Run: sudo chmod a+rw $port   (or add yourself to 'dialout')"; exit 1; }
  write_config
  echo "== compiling $sketch"
  "$CLI" compile --fqbn "$FQBN" "$FW/$sketch" || exit 1
  echo "== uploading to $port (hold the BOOT button if it says 'waiting for download')"
  "$CLI" upload --fqbn "$FQBN" -p "$port" "$FW/$sketch" || exit 1
  grn "== flashed. Opening serial monitor (Ctrl+C to quit)"
  "$CLI" monitor -p "$port" -c baudrate=115200
}

case "${1:-doctor}" in
  doctor) doctor ;;
  check) flash sensor_check "${2:-}" ;;
  node) flash aurasense_node "${2:-}" ;;
  monitor) p=$(find_port "${2:-}"); "$CLI" monitor -p "$p" -c baudrate=115200 ;;
  config) write_config ;;
  *) sed -n '2,10p' "$0" ;;
esac
