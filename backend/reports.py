"""Pre-diagnosed service ticket as PDF, so the repair centre brings the right
part the first time."""
from __future__ import annotations

from pathlib import Path

from fpdf import FPDF

from .config import UPLOAD_DIR
from .models import Case, MachineProfile

FONT_DIR = Path("/usr/share/fonts/truetype")
FONTS = {
    "body": FONT_DIR / "dejavu/DejaVuSans.ttf",
    "bold": FONT_DIR / "dejavu/DejaVuSans-Bold.ttf",
    "Hindi": FONT_DIR / "noto/NotoSansDevanagari-Regular.ttf",
    "Kannada": FONT_DIR / "noto/NotoSansKannada-Regular.ttf",
}
SEV_RGB = {"LOW": (46, 125, 50), "MEDIUM": (237, 160, 0), "HIGH": (230, 81, 0), "CRITICAL": (198, 40, 40)}


class _PDF(FPDF):
    def header(self):
        self.set_font(self._f, "B", 14)
        self.cell(0, 8, "AuraSense - Pre-diagnosed Service Ticket", new_x="LMARGIN", new_y="NEXT")
        self.set_font(self._f, "", 8)
        self.set_text_color(110)
        self.cell(0, 5, "AI-generated by Gemma 4 (local). Verify on site before acting.", new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(0)
        self.ln(2)


def _setup() -> _PDF:
    pdf = _PDF()
    if FONTS["body"].exists():
        pdf.add_font("dv", "", str(FONTS["body"]))
        pdf.add_font("dv", "B", str(FONTS["bold"]))
        pdf._f = "dv"
    else:
        pdf._f = "helvetica"
    try:
        pdf.set_text_shaping(True)
    except Exception:  # noqa: BLE001
        pass
    pdf.set_auto_page_break(True, 14)
    pdf.add_page()
    return pdf


def _h(pdf, t):
    pdf.ln(2)
    pdf.set_font(pdf._f, "B", 11)
    pdf.cell(0, 7, t, new_x="LMARGIN", new_y="NEXT")
    pdf.set_font(pdf._f, "", 9)


def _p(pdf, t):
    pdf.multi_cell(0, 5, str(t), new_x="LMARGIN", new_y="NEXT")


def build_ticket(case: Case, machine: MachineProfile, centre: dict | None) -> bytes:
    pdf = _setup()
    d = case.diagnosis or {}
    wo = case.work_order or {}
    au = case.audit or {}
    rep = case.report or {}
    pdf.set_font(pdf._f, "", 9)
    _p(pdf, f"Case {case.id}   |   Opened {case.opened_at:%d %b %Y %H:%M} UTC   |   Status {case.status}")
    _p(pdf, f"Machine: {machine.name} ({machine.machine_type}, {machine.power_kw or '?'} kW, {machine.rated_rpm or '?'} rpm)"
            f" - {machine.location}")
    if centre:
        _p(pdf, f"Assigned to: {centre['name']} - {centre['area']} - {centre['phone']}")

    sev = d.get("severity", "MEDIUM")
    pdf.ln(2)
    pdf.set_fill_color(*SEV_RGB.get(sev, (90, 90, 90)))
    pdf.set_text_color(255)
    pdf.set_font(pdf._f, "B", 12)
    pdf.cell(0, 9, f" {sev}: {d.get('fault', 'n/a')} - {d.get('component', '')}", fill=True,
             new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0)
    pdf.set_font(pdf._f, "", 9)
    _p(pdf, f"Confidence {round(100 * d.get('confidence', 0))}%  |  Time to failure: {d.get('time_to_failure', '?')}"
            f"  |  Health score: {case.health_score if case.health_score is not None else '?'} / 100")
    _p(pdf, f"Immediate action: {d.get('immediate_action', '')}")

    _h(pdf, "Evidence (multimodal)")
    for k, label in (("evidence_telemetry", "Sensors"), ("evidence_image", "Photo"), ("evidence_audio", "Sound"),
                     ("evidence_baseline", "vs. healthy baseline"), ("roi_findings", "Marked region")):
        if d.get(k):
            _p(pdf, f"- {label}: {d[k]}")
    if d.get("cross_modal_reasoning"):
        _p(pdf, f"Reasoning: {d['cross_modal_reasoning']}")

    if case.evidence.images:
        img = UPLOAD_DIR / case.evidence.images[0]
        if img.exists():
            try:
                pdf.image(str(img), w=70)
            except Exception:  # noqa: BLE001
                pass

    _h(pdf, "Safety first (Safety Auditor)")
    for s in au.get("added_safety_steps", []):
        _p(pdf, f"- {s}")
    if au.get("ppe"):
        _p(pdf, "PPE: " + ", ".join(au["ppe"]))

    _h(pdf, "Repair steps")
    for i, s in enumerate(d.get("repair_steps", []), 1):
        _p(pdf, f"{i}. {s}")
    if d.get("manual_refs"):
        _h(pdf, "Manual references")
        for r in d["manual_refs"]:
            _p(pdf, f"- {r.get('doc')} p.{r.get('page')} {r.get('section', '')}: \"{r.get('quote', '')}\"")

    if wo:
        _h(pdf, "Work order")
        _p(pdf, f"{wo.get('title')}  |  {wo.get('priority')}  |  est. downtime {wo.get('est_downtime_hours')} h"
                f"  |  est. cost Rs {wo.get('est_total_cost_inr')}")
        for prt in wo.get("parts", []):
            _p(pdf, f"- {prt.get('qty')} x {prt.get('part')} (~Rs {prt.get('est_cost_inr')})")
        if wo.get("skills_needed"):
            _p(pdf, "Skills: " + ", ".join(wo["skills_needed"]))

    if rep.get("operator_message_local"):
        _h(pdf, "Operator message")
        _p(pdf, rep.get("operator_message_en", ""))
        lang = case.evidence.language
        if lang in ("Hindi", "Kannada") and FONTS[lang].exists():
            pdf.add_font(lang, "", str(FONTS[lang]))
            pdf.set_font(lang, "", 10)
            _p(pdf, rep["operator_message_local"])
            pdf.set_font(pdf._f, "", 9)
    return bytes(pdf.output())
